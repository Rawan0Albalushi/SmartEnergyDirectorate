export type Locale = 'ar' | 'en';
export type TranslationKey = keyof typeof ar;

const dictionaries: Record<Locale, { [K in TranslationKey]: string }> = { ar, en };

const labels = {
    planned: 'planned',
    ongoing: 'ongoing',
    completed: 'completed',
    local: 'local',
    international: 'international',
    pending: 'pending',
    published: 'published',
    rejected: 'rejected',
    manual: 'manual',
    fetched: 'fetched',
    staff: 'staff',
    board: 'board',
} as const satisfies Record<string, TranslationKey>;

export function translate(locale: Locale, key: TranslationKey): string {
    return dictionaries[locale][key];
}

export function label(locale: Locale, value: string): string {
    const key = labels[value as keyof typeof labels];

    return key ? translate(locale, key) : value;
}

export function useI18n() {
    const props = usePage().props as {
        locale?: string;
        alternates?: { ar: string; en: string };
    };
    const locale: Locale = props.locale === 'en' ? 'en' : 'ar';

    return {
        locale,
        dir: locale === 'ar' ? 'rtl' : 'ltr',
        alternates: props.alternates ?? { ar: '/ar', en: '/en' },
        t: (key: TranslationKey) => translate(locale, key),
    };
}
